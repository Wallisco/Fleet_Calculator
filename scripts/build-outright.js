#!/usr/bin/env node
'use strict';
/**
 * Builds the OUTRIGHT-PURCHASE-ONLY calculator.
 *
 *   node scripts/build-outright.js [service-url]
 *   npm run build:outright
 *
 * Same source, same model, same server, same PDF pipeline. The funding choice is
 * locked to 'buy' and the lease-only controls are suppressed with CSS rather than
 * cut out of the markup — the shared render() then runs completely unmodified, so
 * this build can never drift from the full one.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const API = process.argv[2] || process.env.SERVICE_URL ||
  'https://scoothero-calculator.onrender.com';

let html = fs.readFileSync(path.join(ROOT, 'public', 'index.html'), 'utf8');
const model = fs.readFileSync(path.join(ROOT, 'public', 'model.js'), 'utf8');

/* Lease-only furniture, suppressed. Everything here is irrelevant when fund==='buy'
   and most of it is already hidden at runtime; this makes it unreachable. */
const HIDE_CSS = `
<style>
  /* outright build */
  #fundLbl + .seg,            /* funding selector      */
  #rateField,                 /* lease interest rate   */
  #petrolWrap,                /* petrol cost inputs    */
  #costCmpSec,                /* cost-vs-petrol table  */
  #s-fuel, #keyFuel,          /* energy segment        */
  #kmWrap,                    /* km assumption         */
  #cmpSec                     /* three-way comparison  */
  { display: none !important; }

  .fixed-fund{
    display:inline-block;padding:10px 16px;border-radius:10px;
    background:var(--navy);color:#fff;font-family:'Lexend',sans-serif;
    font-size:12.5px;font-weight:500;
  }
</style>`;

/* Static label in place of the selector. */
html = html.replace(
  /<div class="seg" role="group" aria-labelledby="fundLbl">/,
  '<div class="fixed-fund">Bought outright</div>\n        <div class="seg" role="group" aria-labelledby="fundLbl" hidden>'
);
html = html.replace(
  '<p class="hint" id="fundHint">You own the bikes from day one.</p>',
  '<p class="hint" id="fundHint">You own the bikes from day one. Ask us about lease options if you would rather not tie up the capital.</p>'
);

/* Tag the three-way comparison so the CSS above can reach it. */
html = html.replace(
  '<section class="sec" aria-label="Compare the three ways to pay">',
  '<section class="sec" id="cmpSec" aria-label="Compare the three ways to pay">'
);

/* Copy tweak — there is only one way to pay in this build. */
html = html.replace(
  'Set the number of bikes and how you want to pay for them.',
  'Set the number of bikes you would buy.'
);

const TAG = '<script src="model.js"></script>';
html = html.replace(TAG,
  HIDE_CSS + '\n<script>\n/* --- model.js (inlined) --- */\n' + model + '\n</script>\n' +
  '<script>window.SH_API = ' + JSON.stringify(API) + ';</script>');

const banner =
  '<!-- ScootHero fleet calculator — OUTRIGHT PURCHASE build.\n' +
  '     Generated ' + new Date().toISOString().slice(0, 10) + ' by scripts/build-outright.js.\n' +
  '     Edit public/index.html or public/model.js and rebuild; do not edit this file. -->\n';

const dist = path.join(ROOT, 'dist');
fs.mkdirSync(dist, { recursive: true });
const file = path.join(dist, 'calculator-outright.html');
fs.writeFileSync(file, banner + html);

console.log('Wrote ' + path.relative(ROOT, file));
console.log('  size:     ' + ((banner + html).length / 1024).toFixed(1) + ' KB');
console.log('  posts to: ' + API);
